"""Check every number the documents state against the report it comes from (audit A07 R1, R2).

    python scripts/check_claims.py            # fail if a claimed number is missing from a document
    python scripts/check_claims.py --orphans  # also list numbers in the documents no claim covers

docs/claims.yml lists each claim: an expression over the reports, a format, the sentence it appears
in (with {} where the number goes) and the documents that must contain that sentence. When a rerun
changes a number, this check fails until every document says the new one, so a document can never
quietly disagree with reports/. Tables between <!-- BEGIN/END --> markers are generated by
scripts/render_tables.py and are not listed here.
"""

from __future__ import annotations

import json
import math
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from truelift.economics import Terms, fmt_inr, weekly_example  # noqa: E402

WORDS = {2: "two", 3: "three", 4: "four", 5: "five", 6: "six", 7: "seven", 8: "eight", 9: "nine", 10: "ten"}


class Dot(dict):
    """Read nested JSON with dots: ev.main.policies.truelift.offers_that_pay; keys like "10%" with [ ]."""

    def __getattr__(self, k):
        try:
            v = self[k]
        except KeyError as e:
            raise AttributeError(k) from e
        return Dot(v) if isinstance(v, dict) else v

    def __getitem__(self, k):
        v = dict.__getitem__(self, k)
        return Dot(v) if isinstance(v, dict) else v


def load(name: str) -> Dot:
    p = ROOT / "reports" / name
    return Dot(json.loads(p.read_text(encoding="utf-8"))) if p.exists() else Dot()


def precision_95(p0: float, p1: float, visits: float, holdout: float, weeks: float = 1) -> float:
    """Half-width, in points, of a 95% range for the lift measured from one offer's own control group."""
    n_t, n_c = visits * weeks * (1 - holdout), visits * weeks * holdout
    return 196 * ((p1 * (1 - p1) / n_t + p0 * (1 - p0) / n_c) ** 0.5)


def half_up(x: float) -> int:
    """Round halves up, as the page does (JavaScript Math.round), so a document and the page always
    show the same whole number (Python's round() sends 64.5 to 64)."""
    return math.floor(x + 0.5)


def fmt(value, how: str) -> str:
    if how == "int":
        return f"{half_up(value):,}"
    if how == "plain":
        return str(half_up(value))
    if how == "pct0":
        return f"{half_up(100 * value)}%"
    if how == "pct1":
        return f"{100 * value:.1f}%"
    if how == "inr":
        return fmt_inr(value)
    if how == "inr_signed":
        return fmt_inr(value, True)
    if how == "inr2":
        return f"₹{value:,.2f}"
    if how == "lakh2":
        return f"₹{abs(value) / 1e5:.2f} lakh"
    if how == "f1":
        return f"{value:.1f}"
    if how == "f3":
        return f"{value:.3f}"
    if how == "f2":
        return f"{value:.2f}"
    if how == "word":
        return WORDS[half_up(value)]
    raise ValueError(f"unknown format {how!r}")


def namespace() -> dict:
    ex = weekly_example()
    pre = weekly_example(Terms(commission_on="pre_discount"))
    return {
        "ev": load("evaluation.json"),
        "criteo": load("uplift_validation_criteo.json"),
        "hill": load("uplift_validation_hillstrom.json"),
        "pilot": load("pilot_sample_size.json"),
        "bench": load("learner_benchmark.json"),
        "sens": load("sensitivity.json"),
        "lat": load("latency.json"),
        "ex": Dot(ex),
        "pre": Dot(pre),
        "precision_95": precision_95,
        "exp": lambda name: load(f"exp_{name}.json").result,
        "round": round,
        "min": min,
        "max": max,
        "abs": abs,
        "sum": sum,
        "len": len,
        "all": all,
        "any": any,
        "zip": zip,
    }


def check(claims: list[dict], ns: dict) -> list[str]:
    problems = []
    for c in claims:
        try:
            value = eval(c["expr"], {"__builtins__": {}, **ns})  # noqa: S307 (our own ledger, not input)
            text = c["text"].replace("{}", fmt(value, c.get("format", "plain")))
        except Exception as e:  # a renamed report key is a failure, with the claim that broke
            problems.append(f"{c['id']}: cannot compute ({type(e).__name__}: {e})")
            continue
        for doc in c["docs"]:
            body = (ROOT / doc).read_text(encoding="utf-8")
            if text not in " ".join(body.split()):
                problems.append(f"{c['id']}: {doc} should say {text!r}")
    return problems


NUMBER = re.compile(r"(?:[−+-]?₹[\d,]+(?:\.\d+)?(?: lakh| Cr)?|\b\d+(?:\.\d+)?%)")


def orphans(claims: list[dict], ns: dict) -> list[str]:
    """Money and percentages in the checked documents that no claim covers (informational)."""
    covered: dict[str, set] = {}
    for c in claims:
        try:
            value = eval(c["expr"], {"__builtins__": {}, **ns})  # noqa: S307
            covered.setdefault(fmt(value, c.get("format", "plain")), set()).update(c["docs"])
        except Exception:
            continue
    out = []
    docs = sorted({d for c in claims for d in c["docs"]})
    for doc in docs:
        text = (ROOT / doc).read_text(encoding="utf-8")
        text = re.sub(r"<!-- BEGIN:.*?<!-- END:[\w-]+ -->", "", text, flags=re.S)  # generated tables
        for m in NUMBER.finditer(text):
            if not any(m.group(0).lstrip("+−-") in k for k in covered):
                out.append(f"{doc}: {m.group(0)}")
    return out


def main() -> int:
    ledger = yaml.safe_load((ROOT / "docs/claims.yml").read_text(encoding="utf-8"))
    claims = ledger["claims"]
    ns = namespace()
    problems = check(claims, ns)
    if "--orphans" in sys.argv[1:]:
        for o in orphans(claims, ns):
            print("not covered by a claim:", o)
    for p in problems:
        print("CLAIM FAILED", p)
    print(f"{len(claims) - len({p.split(':')[0] for p in problems})} of {len(claims)} claims hold")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
